"use strict";
/* ─── Текст всего набора smoke одной строкой ─────────────────────────────────
   Зачем. Несколько наборов (yc-billing, yc-cdn, yc-compute, yc-db, yc-registry,
   yc-storage, yc-ui) читают текст smoke-набора и проверяют, что его сторож
   следит за нужными строками. Пока набор был одним файлом, выбирать было нечего.
   С части 81 наборы разъезжаются по файлам (test/smoke/*.js), и такой читатель
   должен видеть ВЕСЬ набор, а не первый файл.

   Что отдаёт: одну строку — тексты всех файлов набора (test/smoke.test.js, затем
   группы по имени), склеенные переводом строки. Список файлов и их порядок
   держит test/smoke/map.js — тот же модуль, что и у карты, поэтому читатель и
   карта всегда смотрят на один и тот же набор.

   Подключается через require, сам не запускается. */

module.exports = require("./map.js")
  .setSources()
  .map((s) => s.text)
  .join("\n");
