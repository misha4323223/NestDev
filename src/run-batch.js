"use strict";

/* ─── Решения после раунда: пустой ответ, граница батча, закрытие работы ──────
   Вынесено из main.js (этап B, часть 19б — седьмой заход в ядро чата runAi).

   Раунд закончился. Здесь решается, что дальше: попросить итоговый отчёт,
   начать следующий батч (тот же контекст), закрыть работу или выйти из цикла.
   Ошибки тут тихие и дорогие:

     • **молчание вместо отчёта** — модель закончила действия с пустым ответом,
       и человек не получает ни работы, ни объяснения, что сделано;
     • **повторный отчёт по кругу** — просьба «напиши отчёт» уходит больше одного
       раза, и чат заполняется одинаковыми сообщениями;
     • **преждевременный финал** — закрытая миссия подаётся как «превышено число
       раундов»: успешная работа выглядит как отказ приложения;
     • **батч без напоминания** — следующий батч идёт без напоминания человеку и
       без сообщения в историю, и модель повторяет уже сделанное;
     • **история меняется после паузы** — порядок «напоминание в историю, затем
       пауза» важен: иначе следующий запрос уходит со старым контекстом.

   Живые значения — аргументами и объектами: миссия и emit приходят объектами,
   история — аргументом. Возвращается решение, а не действие: `end` (завершить
   прогон с текстом), `break` (обычный финал без ошибки) и `continue` (батч живёт
   дальше — модуль уже сказал человеку, дописал историю и выждал паузу). */

function createRunBatch(deps) {
  const {
    emit,
    mission,
    // Пауза между батчами: провайдеру и интерфейсу нужно вздохнуть.
    pauseMs,
  } = deps;

  const pause = typeof pauseMs === "number" ? pauseMs : 1500;

  // Пустой финальный ответ — не молчим. Один раз просим итоговый отчёт.
  // Возвращает true, если просьба отправлена и раунд надо повторить.
  const askForReport = (history, o) => {
    const emptyFinal =
      o.toolCalls.length === 0 &&
      !o.planMode &&
      !o.reportRetried &&
      !String(o.text || "").trim() &&
      !o.aborted;
    if (!emptyFinal) return false;
    history.push({
      role: "user",
      content:
        "Ты завершил действия, но итоговый ответ получился пустым. Напиши структурированный итоговый отчёт: что сделано, какие файлы созданы/изменены, какие команды выполнялись, как проверить результат.",
    });
    return true;
  };

  // Конец батча: миссия жива — продолжаем следующим батчом (тот же контекст),
  // лимиты/зацикливание — мягкая остановка с сохранением работы, без ошибки в чате.
  const afterRound = async (history) => {
    const afterBatch = await mission.afterBatch();
    if (afterBatch.finish) {
      mission.emitState(afterBatch.phase);
      // Работа сохранена, но не закончена (лимит, время, зацикливание): в окне
      // загорится «▶ Продолжить» — раньше человек писал «продолжай» руками.
      return { kind: "end", message: afterBatch.message, resume: true };
    }
    if (!afterBatch.continue) {
      // Миссия закрыта — это НЕ исчерпание счётчика раундов: завершаем обычным
      // финалом. Иначе успешная работа обрывалась бы грозным «превышено число
      // раундов», и это выглядело бы как «агент ни с того ни с сего отвалился».
      if (afterBatch.closed) {
        const mDone = mission.refresh();
        return {
          kind: "end",
          message:
            "🏁 Работа закончена" + (mDone ? " — миссия «" + mDone.title + "» закрыта" : "") +
            ". Цель, план, журнал и отчёт: " + mission.folderText(mDone) + ".",
          // Миссия закрыта — продолжать нечего: кнопка «▶ Продолжить» не показывается.
          resume: false,
        };
      }
      return { kind: "break" };
    }
    // Продолжаем батч: напоминание в чат и в историю, событие миссии — и короткая
    // пауза, чтобы провайдер и интерфейс вздохнули (история при этом не меняется).
    emit({ type: "notice", text: afterBatch.notice });
    mission.emitState(afterBatch.phase);
    history.push({ role: "user", content: afterBatch.historyMessage });
    await new Promise((r) => setTimeout(r, pause));
    return { kind: "continue" };
  };

  return { askForReport: askForReport, afterRound: afterRound };
}

module.exports = { createRunBatch };
