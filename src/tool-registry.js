/* ─── Реестр агентских инструментов и вызов инструмента ──────────────────────
   Вынесено из main.js (этап B, часть 35). Здесь два связанных дела, которые
   раньше стояли в оболочке врозь: сборка обработчиков (в конце файла) и сам
   вызов инструмента (в середине) — и держались друг за друга через переменную
   `agentToolHandlers`.

     • СБОРКА: createAgentTools получает ~120 имён — всё, чем живут инструменты
       (файлы, оболочки, сеть, браузер, облако, миссии, окно). Собирается один раз
       при загрузке и последней в файле: к этому месту построены все модули.
     • ВЫЗОВ (executeTool): выбор обработчика, объявление назначения (capability) на
       время вызова, немедленная остановка по «Стоп» и единая обёртка ошибки.

   Почему это место дорогое. Ошибки тут тихие и всплывают у пользователя:

     • потерянное имя в списке — инструмент отвечает «X is not defined» ровно в
       момент вызова, в одной задаче, и со стороны выглядит как «модель тупит»;
     • забытый возврат назначения — после инструмента с другим назначением агент
       оставил бы себе чужие переменные окружения (или потерял свои) до конца
       прогона, а видно это только по «не найдено» внутри команд;
     • исключение из обработчика, ушедшее наружу, рвёт весь прогон вместо того,
       чтобы вернуть модели текст ошибки — и модель не может исправиться.

   Живое здесь — назначение окружения: getCapability/setCapability принадлежат
   экземпляру src/agent-env.js, собранному в оболочке (своя копия модуля дала бы
   другой экземпляр и пустое назначение). Стоп-флаг читается глобальным
   (global.__agentStopRequested): его ставит канал ai:stop и каналы миссий, читает
   весь прогон — так же, как это делают run-ai.js и mission-ipc.js.

   Список имён уходит в createAgentTools ТЕМ ЖЕ плоским объектом, что оболочка
   передала сюда: отдельный объект для инструментов разъехался бы с проводкой, а
   страж связи (test/backend-wiring.js) сверяет имена по распаковке agent-tools.js.
   Проверка «все имена реестра переданы» стоит в test/tool-registry.test.js.

   Тексты подтверждений живут в политике (tool-policy.js) — describeToolArgs только
   обёртка над toolPolicy.describe, поэтому она рядом: этим именем пользуются прогон
   (run-ai) и строгая очередь (run-strict), когда показывают человеку, что именно
   будет выполнено. */

const toolPolicy = require("./tool-policy.js");

// Короткое описание аргументов для подтверждения опасного действия.
function describeToolArgs(name, a) {
  return toolPolicy.describe(name, a);
}

function createToolRegistry(deps) {
  const { createAgentTools, fmtError, getCapability, setCapability } = deps;

  // Обработчики собираются ОДИН раз: deps — тот самый плоский список имён, что
  // пришёл из оболочки (плюс четыре имени для нас, их инструменты просто не берут).
  const handlers = createAgentTools(deps);

  async function executeTool(name, args, settings) {
    args = args || {};
    // Инструмент в работе: его capability решает, какие переменные агента дойдут до
    // команд внутри него. Вызовы инструментов идут по очереди (цикл runAi), поэтому
    // одного «текущего назначения» достаточно; вложенный вызов вернёт своё.
    const prevCapability = getCapability();
    setCapability(toolPolicy.capabilityOf(name));
    try {
      // Пользователь нажал Esc/«Стоп» — агент должен немедленно остановиться.
      if (global.__agentStopRequested) {
        return "⏹ Остановлено пользователем (Esc / Стоп). Немедленно прекрати вызовы инструментов и заверши ответ КРАТКИМ итогом: что успел сделать и что осталось.";
      }
      // Обработчики вынесены в src/agent-tools.js (1.5.77): здесь только выбор
      // инструмента и единая обработка ошибок — как и раньше.
      const handler = handlers[name];
      if (!handler) return "Ошибка: неизвестный инструмент " + name;
      return await handler(args, settings);
    } catch (e) {
      return "Ошибка: " + fmtError(e);
    } finally {
      setCapability(prevCapability);
    }
  }

  return { executeTool };
}

module.exports = { createToolRegistry, describeToolArgs };
