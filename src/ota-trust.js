/* ─── Кому приложение доверяет подпись OTA-наборов ────────────────────────────
   Набор кода (ota/bundle.json + manifest.json) исполняется в приложении, поэтому
   его подпись — то же самое, что подпись кода обновления. До этого файла
   целостность набора держалась на sha256 в манифесте, а манифест лежит РЯДОМ с
   набором: кто положил поддельный bundle.json, тот положит и свой манифест, и
   хеш сойдётся. Подпись так не подделать — закрытый ключ есть только у вас.

   Список пуст — приложение работает как раньше (наборы без подписи принимаются),
   но панель «Обновление кода» говорит об этом прямо. Как только здесь появится
   хотя бы один ключ, принимаются ТОЛЬКО наборы, подписанные им: неподписанный
   или подписанный чужим ключом набор отклоняется с объяснением.

   Как завести свой ключ (закрытая часть остаётся у вас и в репозиторий не едет):

       npm run ota:key            # создаст ключ и напечатает открытую часть
       npm run ota:key -- --trust # создаст и впишет открытую часть в этот файл

   Ключ по умолчанию: ~/.ai-agent-ota-key.pem (Ed25519 — короткий и быстрый).
   Сборка набора теперь подписывает его этим ключом (scripts/make-ota.js), а
   приложение проверяет подпись ДО распаковки (src/ota.js → src/ota-sign.js).

   Строки ниже можно править руками и добавлять вторым, третьим ключом: пока
   подпись сходится с любым из списка, набор применяется. Так же делается смена
   ключа без простоя — сначала добавляется новый, потом убирается старый. */

