"use strict";

/* ─── Призывы по текстовому ответу: план не закрыт и сторож миссии ────────────
   Вынесено из main.js (этап B, часть 20 — восьмой заход в ядро чата runAi).

   Модель ответила ТЕКСТОМ без вызова инструментов. Это ещё не финал: слабые
   (особенно локальные) модели на выросшем или сжатом контексте «забывают» вызвать
   инструмент и просто описывают, что осталось. Раньше прогон на этом заканчивался,
   и агент выглядел отключившимся. Здесь решается, призвать ли его продолжить делом.

   Ошибки на этом шаге тихие и дорогие:

     • **призыв по кругу** — просьба «продолжай делом» уходит без счётчика, и человек
       получает три одинаковых отчёта подряд (именно так и было);
     • **призыв после «Стоп»** — прогон, который человек только что остановил, снова
       зовёт модель, и работа идёт вопреки остановке;
     • **призыв в режиме плана** — план ещё не закрыт, но инструменты там не работают:
       призыв «вызови инструмент» уводит модель в запрещённую зону;
     • **план закрыт, а призыв всё равно ушёл** — модель делает лишний круг и тратит
       токены на «продолжи работу», когда работы не осталось;
     • **пауза сторожа не заканчивает призывы** — петля призывов живёт дальше и жжёт
       лимиты вместо того, чтобы отдать работу человеку.

   Живые значения — аргументами и объектами: история приходит массивом (модуль в неё
   пишет), сводка плана — функцией (её меняет панель плана в любой момент), миссия и
   эмиттеры — объектами. Решение возвращается наружу: `repeat` (раунд повторить),
   `pause` (миссия встала на паузу — призывы кончились, но прогон идёт дальше обычным
   финалом) и `none` (призывать нечего). Повтор раунда делает прогон. */

function createRunNudge(deps) {
  const {
    emit,
    termEmit,
    mission,
    // Сводка плана работ — живым значением: её пишет панель плана.
    getPlanSummary,
  } = deps;

  // «План не закрыт, а модель замолчала» — просим продолжить делом (макс. 2).
  // Счётчик принадлежит прогону: модуль собирается один раз на прогон.
  let planNudges = 0;

  const decide = (history, o) => {
    // Призыв уместен только когда ответило текстом и прогон не остановлен.
    if (o.toolCalls.length || o.planMode || o.aborted) return { action: "none" };

    // 1. План не закрыт — это обрыв, а не финал.
    const plan = getPlanSummary();
    if (
      planNudges < 2 &&
      plan &&
      plan.total > 0 &&
      plan.done + plan.failed < plan.total
    ) {
      planNudges++;
      const left = plan.total - plan.done - plan.failed;
      termEmit({
        type: "metrics",
        text: "📋 План не закрыт (" + left + " из " + plan.total + " пунктов) — прошу агента продолжить делом (попытка " + planNudges + "/2).",
      });
      history.push({
        role: "user",
        content:
          "Ты ответил текстом, но план работ не закрыт: " + plan.done + " из " + plan.total + " готово" +
          (plan.failed ? ", сбоев: " + plan.failed : "") +
          ". Работа не окончена — не описывай, что осталось, а ВЫПОЛНЯЙ: вызови следующий инструмент. " +
          "Если пункт выполнить нельзя — отметь его failed через todoWrite (с причиной в note) и переходи к следующему. " +
          "После каждого шага присылай todoWrite с ПОЛНЫМ списком.",
      });
      return { action: "repeat" };
    }

    // 2. Миссия не закрыта, а модель ответила текстом. Призывать ли дальше — решает
    // сторож (src/mission-guard.js): один призыв на первый текстовый ответ, дальше —
    // только если работа сдвинулась. Повтор того же ответа или стояние на месте
    // прекращает призывы и уводит миссию в паузу.
    if (mission.canNudge()) {
      const nudge = mission.nudge(o.text);
      if (nudge.action === "nudge") {
        emit({ type: "notice", text: nudge.notice });
        history.push({ role: "user", content: nudge.historyMessage });
        return { action: "repeat" };
      }
      if (nudge.action === "pause") {
        // Призывы прекращены: миссия встаёт на паузу и ждёт человека. Пауза сама
        // не подхватывается следующим прогоном — на этом петля и кончается.
        emit({ type: "notice", text: nudge.notice });
        mission.emitState(nudge.phase);
        mission.refresh(); // пауза не подхватывается сама: дальше работа идёт как обычная
        return { action: "pause" };
      }
    }

    return { action: "none" };
  };

  return { decide: decide };
}

module.exports = { createRunNudge };
