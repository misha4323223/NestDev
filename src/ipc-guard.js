"use strict";

/* ─── Кто имеет право звать канал ─────────────────────────────────────────────
   Зачем отдельный модуль. У ядра приложения два законных клиента: окно на ПК
   (наш рендерер с preload) и мост телефона (своё подключение по PIN). До этого
   модуля разрушительные каналы (undo:rollback, fs:delete, term:*, ai:send) не
   проверяли отправителя вообще — они держались только на том, что «кроме окна
   никто позвать не может». Это правда ровно до первого второго окна,
   встроенного просмотра или нового webContents: любой рендерер внутри
   приложения получает доступ к тем же каналам, и один вызов `ai:send` или
   `fs:delete` проходит без единого вопроса.

   Как различаем отправителя. Электрон сам подставляет в событие и `sender`
   (webContents), и `senderFrame` (кадр вызова) — подделать их из рендерера
   нельзя, аргументы вызова и событие идут разными путями:

     • события нет вовсе → канал позвали ВНУТРИ приложения (сам main, наборы,
       живой прогон) — это не рендерер, спрашивать нечего. Разрешаем;
     • `sender` — это ЖИВОЕ окно приложения (по объекту, а если окно отдало
       только id — по нему) → наш ПК-клиент. Разрешаем;
     • кадр есть, но окно не наше → ЧУЖОЙ рендерер или подрамник. Отказываем;
     • `sender.id === 0` (или id нет) → так зовёт мост телефона: он сам
       собирает событие для обработчика. Разрешаем — политику телефона ведёт
       список разрешённого в src/mobile-bridge.js, а не этот модуль;
     • остальное (положительный чужой id) → неизвестный рендерер. Отказываем.

   Почему сравнение с ЖИВЫМ окном, а не с сохранённым значением: окно
   создаётся позже сборки модуля, пересоздаётся и закрывается, поэтому оно
   приходит функцией. Сравнение по живому объекту не стареет: закрытое окно
   перестаёт подходить, и чужие вызовы перестают проходить.

   Отказ всегда внятный: канал отвечает { ok:false, error } и пишет строку в
   консоль главного процесса — чтобы «почему не работает» не превращалось в
   загадку для человека, который просто нажал кнопку. */

// Мост телефона зовёт обработчики с синтетическим событием IPC: `sender.id = 0`.
// У настоящего рендерера id всегда положительный (это id его webContents).
const MOBILE_SENDER_ID = 0;

const KINDS = {
  desktop: "окно приложения",
  mobile: "телефон",
  direct: "прямой вызов внутри приложения",
  foreign: "чужой рендерер",
};

function webContentsOf(window) {
  if (!window) return null;
  try {
    if (typeof window.isDestroyed === "function" && window.isDestroyed()) return null;
  } catch {}
  return window.webContents || null;
}

// Событие пришло из НАШЕГО окна? Сравниваем по объекту webContents, а если
// отправитель отдал только id — по нему (так зовут живые прогоны: они берут
// `win.webContents.id`). Подделать это из рендерера нельзя: событие собирает
// сам Electron, а не страница.
function isOurWindow(sender, wc) {
  if (!sender || !wc) return false;
  if (sender === wc) return true;
  const a = sender.id;
  const b = wc.id;
  return !!(a && b && a === b);
}

/* Кто позвал канал: "desktop" | "mobile" | "direct" | "foreign". */
function senderKind(event, window) {
  if (!event) return "direct"; // события нет: зовут внутри приложения
  const sender = event.sender;
  const frame = event.senderFrame || null;
  const wc = webContentsOf(window);

  if (frame && frame.parent) return "foreign"; // подрамник: наши клиенты зовут из верхнего кадра
  if (isOurWindow(sender, wc)) return "desktop";
  if (frame) return "foreign"; // кадр есть, но это не наше окно — чужой рендерер
  if (!sender || !sender.id) return "mobile"; // id 0 или нет вовсе — так зовёт мост телефона
  return "foreign"; // чужой webContents без кадра
}

/* Разрешение на вызов: null — можно, иначе готовый текст отказа.
   opts.window — живое окно (функцией или значением), opts.channel — имя канала
   для сообщения человеку и для строки в консоли. */
function denyReason(event, opts) {
  const o = opts || {};
  const kind = senderKind(event, o.window);
  if (kind === "desktop" || kind === "mobile" || kind === "direct") return null;
  const where = (o.channel || "канал") + " вызван не из окна приложения (" + KINDS[kind] + ")";
  try {
    console.error("[ipc] отказ: " + where);
  } catch {}
  return "Отказано: " + where + ". Действие не выполнено.";
}

module.exports = {
  MOBILE_SENDER_ID,
  senderKind,
  denyReason,
};
