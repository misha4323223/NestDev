"use strict";
/* ─── Держатели темпа провайдера: один на «провайдер+модель», общий всем прогонам ──

   Вынесено из оболочки (src/main.js) этапом B, заход 3.

   Зачем это вообще нужно и почему именно так:
   • провайдеры с бесплатными/дешёвыми ключами отвечают 429, если слать запросы
     чаще, чем разрешено (у бесплатных это часто «N запросов в минуту» на КЛЮЧ);
   • темп держит не пауза между раундами, а общий счётчик: если лимитер живёт
     внутри одного прогона, то «Стоп» и новый запуск получают СВОЙ лимитер, шлют
     запросы сразу и снова ловят 429 — это и было жалобой «после Стоп не работает»;
   • поэтому карта живёт в замыкании фабрики, а фабрика собирается ОДИН раз в
     оболочке: все прогоны, все чаты и мобильный клиент берут один и тот же объект.

   Ключ — «провайдер|модель», а не сам ключ доступа: секрет не попадает в ключ
   карты (карту видно в отладке), а поведение то же — у бесплатных тарифов лимит
   привязан к паре «провайдер + модель», у платных он мягче и счётчик не мешает.

   Модуль не знает ни о настройках, ни о сети: `createRateLimiter` приходит
   значением (в оболочке это ядро агента), поэтому проверяется обычным тестом. */

function createRateLimiters(deps) {
  const { createRateLimiter } = deps || {};
  if (typeof createRateLimiter !== "function") {
    throw new Error("Держатели темпа: createRateLimiter обязателен.");
  }
  const byKey = new Map(); // «провайдер|модель» → лимитер (общий на все прогоны)

  // Лимитер для настроек прогона. Один и тот же объект возвращается столько раз,
  // сколько раз его спросят, — в этом весь смысл: пауза после 429, запомненная
  // одним прогоном, действует и для следующего.
  const rateLimiterFor = (settings) => {
    const s = settings || {};
    const key = String(s.provider || "openai") + "|" + String(s.model || "");
    if (!byKey.has(key)) byKey.set(key, createRateLimiter());
    return byKey.get(key);
  };

  // Сколько пар «провайдер+модель» уже держат свой темп — для проверок и отладки.
  const rateLimiterKeys = () => [...byKey.keys()];

  return { rateLimiterFor, rateLimiterKeys };
}

module.exports = { createRateLimiters };
